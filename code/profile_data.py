"""Profile the preprocessed corpus.

Writes:
  data/profile/corpus_profile.md   human-readable corpus statistics
  data/profile/filter_values.json  observed values (with counts) for each filterable field;
                                   the allowed values for the build_filter tool schema

Usage: python code/preprocess.py && python code/profile_data.py
"""

import json
import re
from collections import Counter
from pathlib import Path

import duckdb

from preprocess import DB_PATH, ROOT, load_abbreviations

OUT_DIR = ROOT / "data/profile"
ASRS_ABBR = ROOT / "data/reference/asrs_abbreviations.json"

# Fields the build_filter tool may constrain. List-typed columns are unnested before counting.
FILTER_FIELDS = [
    "time_of_day", "light", "aircraft_family", "make_model", "aircraft_operator", "far_part", "mission", "flight_phase",
    "maintenance_type", "maintenance_items", "maintenance_deferred", "released_for_service",
    "component", "component_problem", "reporter_function", "reporter_organization",
    "human_factors", "anomaly", "detector", "when_detected", "result",
    "contributing_factors", "primary_problem",
]
TOP_N = 10

TOKEN = re.compile(r"(?<![\w/])[A-Z][A-Z0-9/]{1,7}(?![\w/])")
# ASRS de-identification placeholders (ZZZ, ZZZZ1, XX, XA00, ...); not abbreviations.
PLACEHOLDER = re.compile(r"Z{3,5}\d*|X+[A-Z]?\d*|Y{3,}\d*|NAME\d*|DATE\d*")


def value_counts(con, field):
    is_list = con.execute(
        "SELECT data_type FROM information_schema.columns WHERE table_name = 'reports' AND column_name = ?",
        [field],
    ).fetchone()[0].endswith("[]")
    source = f"unnest({field})" if is_list else field
    rows = con.execute(
        f"SELECT v, count(*) AS n FROM (SELECT {source} AS v FROM reports) "
        f"WHERE v IS NOT NULL GROUP BY v ORDER BY n DESC, v"
    ).fetchall()
    empty = con.execute(
        f"SELECT count(*) FROM reports WHERE {field} IS NULL" + (f" OR len({field}) = 0" if is_list else "")
    ).fetchone()[0]
    return dict(rows), empty


def abbreviation_coverage(texts):
    """Share of abbreviation-like tokens covered by the ASRS list alone vs. ASRS + supplement."""
    asrs = {a for a, senses in json.loads(ASRS_ABBR.read_text())["abbreviations"].items() if len(senses) == 1}
    combined = set(load_abbreviations())
    tokens = Counter(t for text in texts for t in TOKEN.findall(text) if not PLACEHOLDER.fullmatch(t))
    total = sum(tokens.values())
    asrs_hits = sum(n for t, n in tokens.items() if t in asrs)
    combined_hits = sum(n for t, n in tokens.items() if t in combined)
    expanded = Counter({t: n for t, n in tokens.items() if t in combined})
    return total, asrs_hits, combined_hits, expanded.most_common(TOP_N)


def md_table(headers, rows):
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(lines)


def main():
    OUT_DIR.mkdir(exist_ok=True)
    con = duckdb.connect(str(DB_PATH), read_only=True)

    n_reports = con.execute("SELECT count(*) FROM reports").fetchone()[0]
    n_narr = con.execute("SELECT count(*) FROM narratives").fetchone()[0]
    n_two = con.execute("SELECT count(*) FROM reports WHERE narrative_2 IS NOT NULL").fetchone()[0]
    first, last = con.execute(
        "SELECT min(year * 100 + month), max(year * 100 + month) FROM reports"
    ).fetchone()
    per_year = con.execute("SELECT year, count(*) FROM reports GROUP BY year ORDER BY year").fetchall()
    words = con.execute(
        "SELECT min(w), quantile_cont(w, 0.25), median(w), quantile_cont(w, 0.75), max(w) "
        "FROM (SELECT len(string_split(text, ' ')) AS w FROM narratives)"
    ).fetchone()
    texts = [t for (t,) in con.execute("SELECT text FROM narratives").fetchall()]
    total_tok, asrs_hits, combined_hits, top_expanded = abbreviation_coverage(texts)

    filter_values, field_rows = {}, []
    for field in FILTER_FIELDS:
        counts, empty = value_counts(con, field)
        filter_values[field] = counts
        top = "; ".join(f"{v} ({n})" for v, n in list(counts.items())[:3])
        field_rows.append((f"`{field}`", len(counts), f"{100 * (n_reports - empty) / n_reports:.0f}%", top))
    filter_values = {"year": {"min": first // 100, "max": last // 100}, **filter_values}

    (OUT_DIR / "filter_values.json").write_text(json.dumps(filter_values, indent=2) + "\n")

    sections = [
        "# Corpus Profile",
        "Generated by `code/profile_data.py` from `data/raw/asrs_maint_2010_2026.csv`.",
        "## Overview",
        md_table(["Metric", "Value"], [
            ("Reports (unique ACNs)", n_reports),
            ("Incident dates", f"{first // 100}-{first % 100:02d} to {last // 100}-{last % 100:02d}"),
            ("Reports with a second reporter narrative", f"{n_two} ({100 * n_two / n_reports:.0f}%)"),
            ("Narratives (retrieval units)", n_narr),
            ("Narrative length, words (min / Q1 / median / Q3 / max)", " / ".join(f"{w:.0f}" for w in words)),
        ]),
        "## Reports per Year",
        "2026 is a partial year (ASRS publishes reports with a processing lag).",
        md_table(["Year", "Reports"], per_year),
        "## Abbreviation Coverage",
        f"Abbreviation-like tokens (uppercase, 2-8 chars, excluding de-identification placeholders): "
        f"{total_tok:,} ({100 * total_tok / sum(len(t.split()) for t in texts):.1f}% of narrative words).",
        md_table(["Dictionary", "Tokens covered"], [
            ("ASRS list only (unambiguous entries)", f"{asrs_hits:,} ({100 * asrs_hits / total_tok:.0f}%)"),
            ("ASRS + maintenance supplement", f"{combined_hits:,} ({100 * combined_hits / total_tok:.0f}%)"),
        ]),
        "Most frequently expanded: " + ", ".join(f"{t} ({n})" for t, n in top_expanded) + ".",
        "## Filterable Fields",
        "Distinct values and coverage for each field the `build_filter` tool can constrain. "
        "Full value lists are in `filter_values.json`.",
        md_table(["Field", "Distinct values", "Reports with a value", "Top values"], field_rows),
    ]
    (OUT_DIR / "corpus_profile.md").write_text("\n\n".join(sections) + "\n")
    print(f"Wrote {OUT_DIR.relative_to(ROOT)}/corpus_profile.md and filter_values.json")


if __name__ == "__main__":
    main()
