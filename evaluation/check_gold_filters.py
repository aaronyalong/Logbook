"""Validate and execute every gold filter in queries.json; record result counts.

Also checks that validation rejects invented values (the query 19 failure mode).

Usage: python evaluation/check_gold_filters.py
Output: evaluation/gold_filter_results.md
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "code"))

import duckdb  # noqa: E402

from filter_spec import run, validate  # noqa: E402
from preprocess import DB_PATH  # noqa: E402

QUERIES = ROOT / "evaluation/queries.json"
OUT = ROOT / "evaluation/gold_filter_results.md"

INVALID_SPECS = [
    {"where": {"make_model": ["Spacecraft"]}},
    {"where": {"aircraft_type": ["B737"]}},
    {"year_min": 1995},
    {"where": {"aircraft_family": ["Boeing 737"]}},
]


def describe(result):
    if "groups" in result:
        top = "; ".join(f"{v} ({n})" for v, n in list(result["groups"].items())[:3])
        return f"{result['count']} reports; top: {top}"
    return f"{result['count']} report{'' if result['count'] == 1 else 's'}"


def main():
    queries = json.loads(QUERIES.read_text())["queries"]
    con = duckdb.connect(str(DB_PATH), read_only=True)

    rows, failures = [], 0
    for q in queries:
        gold = q["gold_filter"]
        if gold is None:
            if q["filter_scored"]:
                rows.append((q["id"], q["category"], "none (expected empty result)", "0 reports"))
            continue
        specs = gold if isinstance(gold, list) else [gold]
        for spec in specs:
            errors = validate(spec)
            if errors:
                failures += 1
                outcome = "INVALID: " + "; ".join(errors)
            else:
                outcome = describe(run(spec, con))
            rows.append((q["id"], q["category"], f"`{json.dumps(spec)}`", outcome))

    rejected = [(spec, validate(spec)) for spec in INVALID_SPECS]
    failures += sum(1 for _, errors in rejected if not errors)

    lines = [
        "# Gold Filter Results",
        "",
        "Generated by `evaluation/check_gold_filters.py`.",
        "",
        "| Query | Category | Gold filter | Result |",
        "|---|---|---|---|",
        *(f"| {i} | {c} | {f} | {r} |" for i, c, f, r in rows),
        "",
        "## Validation rejects invented filters",
        "",
        "| Spec | Rejected because |",
        "|---|---|",
        *(f"| `{json.dumps(s)}` | {'; '.join(e) or 'NOT REJECTED'} |" for s, e in rejected),
        "",
    ]
    OUT.write_text("\n".join(lines))
    print("\n".join(lines))
    sys.exit(1 if failures else 0)


if __name__ == "__main__":
    main()
